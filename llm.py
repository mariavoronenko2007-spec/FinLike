import os

from dotenv import load_dotenv
from openai import OpenAI

from database import get_database_schema


load_dotenv()


client = OpenAI(
    api_key=os.getenv("YANDEX_API_KEY"),
    base_url="https://ai.api.cloud.yandex.net/v1",
)


def get_role(login):
    if not login:
        return "anon"

    role = login.split("-")[0].lower()

    allowed_roles = {
        "stu",
        "tea",
        "app",
        "adm",
    }

    if role not in allowed_roles:
        return "anon"

    return role


def get_role_rules(role, login):
    if role == "anon":
        return """
Пользователь не авторизован.

Разрешена общая информация об университете.

По студентам, оценкам, абитуриентам и заявлениям
разрешена только общая агрегированная или
обезличенная информация.

Не раскрывай персональные данные конкретных
студентов и абитуриентов.
"""

    if role == "stu":
        return f"""
Пользователь является студентом.
Его логин: {login}.

Студент может получать свои персональные
и учебные данные.

Если пользователь спрашивает о себе,
используй условие:

students.student_code = '{login}'

Не добавляй student_code текущего пользователя,
если вопрос относится к другому конкретному студенту.

Если пользователь спрашивает данные конкретного
другого студента по ФИО или student_code,
не подменяй этого человека текущим пользователем.

Студент не может получать персональные данные
других студентов и абитуриентов.

По другим студентам разрешена только общая
агрегированная или обезличенная информация.

Для собственных оценок используй JOIN grades
со students и фильтр:

students.student_code = '{login}'

Поле ФИО студента:
students.fio_name
"""

    if role == "app":
        return f"""
Пользователь является абитуриентом.
Его логин: {login}.

Абитуриент может получать свои персональные
данные и информацию о своих заявлениях.

Если пользователь спрашивает о себе,
используй условие:

applicants.applicant_code = '{login}'

Для собственных заявлений используй JOIN
applications и applicants и фильтр:

applicants.applicant_code = '{login}'

Абитуриент не может получать персональные данные
других абитуриентов и студентов.

По другим абитуриентам и студентам разрешена
только общая агрегированная или обезличенная информация.

Поле ФИО абитуриента:
applicants.full_name
"""

    if role == "tea":
        return """
Пользователь является преподавателем.

Преподавателю разрешён доступ к учебной информации,
данным студентов, оценкам, дисциплинам,
программам, преподавателям и абитуриентам.

Преподавателю разрешён доступ к персональным
данным студентов и абитуриентов.

Поле ФИО студента:
students.fio_name

Поле ФИО абитуриента:
applicants.full_name
"""

    if role == "adm":
        return """
Пользователь является сотрудником администрации.

Разрешён расширенный доступ к информации
университета, включая студентов, преподавателей,
абитуриентов, заявления, оценки, программы,
факультеты и администрацию.

Администрации разрешён доступ к персональным
данным студентов и абитуриентов.

Поле ФИО студента:
students.fio_name

Поле ФИО абитуриента:
applicants.full_name
"""

    return """
Используй минимальный уровень доступа.
"""


def generate_sql(question, login=None):
    folder_id = os.getenv("YANDEX_FOLDER_ID")
    schema = get_database_schema()

    role = get_role(login)

    role_rules = get_role_rules(
        role,
        login,
    )

    system_prompt = f"""
Ты генерируешь SQL-запросы для PostgreSQL
по вопросам пользователей о данных университета.

Роль пользователя:
{role}

Правила доступа:
{role_rules}

Схема базы данных:

{schema}

Правила:

- Преобразуй вопрос пользователя в SQL-запрос.
- Пользователь задаёт вопросы обычным естественным языком.
- Самостоятельно определяй подходящие таблицы,
  связи, JOIN, фильтры, группировки и сортировку.
- Используй только таблицы и столбцы из схемы.
- Не придумывай таблицы и столбцы.
- При необходимости используй JOIN.
- Для подсчёта используй COUNT.
- Для среднего значения используй AVG.
- Если пользователь просит лучшие результаты,
  используй сортировку по убыванию.
- Если пользователь указывает количество записей,
  используй соответствующий LIMIT.
- При поиске по названиям факультетов, программ,
  дисциплин и ФИО используй ILIKE с %.
- IT означает факультет информационных технологий.
- Для студентов ФИО хранится в students.fio_name.
- Для абитуриентов ФИО хранится в applicants.full_name.
- Соблюдай ограничения текущей роли.
- Не используй INSERT, UPDATE, DELETE, DROP,
  ALTER, CREATE или TRUNCATE.
- Не заменяй запрещённую операцию другим запросом.
- Верни только SQL-запрос.
- Не используй Markdown.
- Не добавляй объяснения.
"""

    response = client.chat.completions.create(
        model=f"gpt://{folder_id}/yandexgpt/latest",
        messages=[
            {
                "role": "system",
                "content": system_prompt,
            },
            {
                "role": "user",
                "content": question,
            },
        ],
        max_tokens=250,
        temperature=0,
    )

    return response.choices[0].message.content.strip()