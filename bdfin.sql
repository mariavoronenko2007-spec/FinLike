CREATE TABLE faculties (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);


CREATE TABLE programs (
    id SERIAL PRIMARY KEY,
    faculty_id INT REFERENCES faculties(id),
    name VARCHAR(200) NOT NULL,
    budget_places INT,
    paid_places INT
);


CREATE TABLE students (
    id SERIAL PRIMARY KEY,
    program_id INT REFERENCES programs(id),
    student_code VARCHAR(20) UNIQUE NOT NULL,
    fio_name VARCHAR(100) NOT NULL,
    enrollment_year INT,
    is_expelled BOOLEAN DEFAULT FALSE
);


CREATE TABLE teachers (
    id SERIAL PRIMARY KEY,
    teacher_code VARCHAR(20) UNIQUE NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    faculty_id INT REFERENCES faculties(id)
);


CREATE TABLE courses (
    id SERIAL PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    teacher_id INT REFERENCES teachers(id),
    semester INT,
    credits INT
);


CREATE TABLE grades (
    id SERIAL PRIMARY KEY,
    student_id INT REFERENCES students(id),
    course_id INT REFERENCES courses(id),
    grade INT CHECK (grade >= 0 AND grade <= 100),
    date_received DATE
);


CREATE TABLE schedule (
    id SERIAL PRIMARY KEY,
    course_id INT REFERENCES courses(id),
    day_of_week INT,
    start_time TIME,
    end_time TIME,
    room VARCHAR(20)
);

CREATE TABLE applicants (
    id SERIAL PRIMARY KEY,
    applicant_code VARCHAR(20) UNIQUE NOT NULL,
    full_name VARCHAR(100) NOT NULL
);

CREATE TABLE applications (
    id SERIAL PRIMARY KEY,
    applicant_id INT REFERENCES applicants(id),
    program_id INT REFERENCES programs(id),
    exam_score INT CHECK (exam_score >= 0 AND exam_score <= 100),
    application_date DATE,
    is_admitted BOOLEAN DEFAULT FALSE
);

CREATE TABLE administration (
    id SERIAL PRIMARY KEY,
    admin_code VARCHAR(20) UNIQUE NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    position VARCHAR(100) NOT NULL,
    faculty_id INT REFERENCES faculties(id)
);


